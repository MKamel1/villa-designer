"""The client's chosen finish schedule (2026-11-23): loader, room table and consistency problems.

knowledge/products/finishes/chosen.json is GENERATED by scripts/build_chosen.py from palettes A/B/C; never hand-edit it.
Slots name the scene material they drive (`scene_material`) and carry the render spec computed from the product
(look-alike image, texture scale from the product format, colour). NO PRICES anywhere.
"""
from __future__ import annotations

import json
from pathlib import Path

from . import finishes

CHOSEN = finishes.PALETTE_DIR / "chosen.json"


def load(path: Path = CHOSEN) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def materials(ch: dict | None = None) -> dict[str, dict]:
    """scene material name -> spec for every slot that is drawn (a name may be driven by one slot only)."""
    ch = ch or load()
    return {n: dict(s["render"]) for s in ch["slots"].values() for n in s.get("scene_materials", [])}


def room_finish(ch: dict | None = None) -> dict[str, tuple[str, str]]:
    """room -> (floor scene material, wall scene material) for rooms the scene draws (not the retained ones)."""
    ch = ch or load()
    out = {}
    for rid, r in ch["rooms"].items():
        if r.get("retained"):
            continue
        out[rid] = (ch["slots"][r["floor"]]["scene_materials"][0], ch["slots"][r["wall"]]["scene_materials"][0])
    return out


# Chosen products whose maker image could not be fetched. Each needs a dated reason; the render keeps its earlier name-based
# estimate and the hand-back says so. Empty this the day the image is sampled (scripts/source_maker_colours.py).
UNSOURCED = {"C-door": "durian.in returns Cloudflare 522 to curl, the browser tool and the Wayback Machine (2026-11-23)"}


def colour_problems(sid: str, s: dict) -> list[str]:
    """A chosen product without a maker-sourced colour fails (never tint by eye)."""
    if s.get("item_id") in UNSOURCED:
        return []
    c = s.get("colour_source") or {}
    if not (c.get("url") and str(c.get("basis", "")).startswith("maker") and c.get("hex")):
        return [f"{sid}: no maker-sourced colour (colour_source needs url, hex and a 'maker ...' basis)"]
    return []


def problems(ch: dict, design_rooms: dict, palettes: dict[str, dict]) -> list[str]:
    """Everything wrong with the schedule: price keys, unlabelled look-alikes, unassigned slots, uncovered rooms."""
    p: list[str] = []
    slots = ch.get("slots", {})
    for sid, s in slots.items():
        item = s.get("item") or {}
        src = palettes.get(s.get("palette"), {})
        ref = next((i for i in src.get("items", []) if i["id"] == s.get("item_id")), None)
        if ref is None:
            p.append(f"{sid}: item {s.get('item_id')!r} not in palette {s.get('palette')!r}")
            continue
        if item != ref:
            p.append(f"{sid}: embedded item differs from palette {s['palette']}")
        p += finishes.item_problems(item)
        p += colour_problems(sid, s)
        if not (s.get("applies_to") or {}).get("rooms") and not s.get("no_geometry"):
            p.append(f"{sid}: applies to no room and no no_geometry reason")
        if not s.get("scene_materials") and not s.get("no_geometry"):
            p.append(f"{sid}: no scene material and no no_geometry reason")
    for rid, r in design_rooms.items():
        c = ch.get("rooms", {}).get(rid)
        if c is None:
            p.append(f"room {rid}: no finish assignment")
            continue
        if c.get("retained"):
            if not c["retained"].get("reason"):
                p.append(f"room {rid}: retained finish without a reason")
            continue
        for k in ("floor", "wall"):
            if c.get(k) not in slots:
                p.append(f"room {rid}: {k} slot {c.get(k)!r} is not a scheduled slot")
        if r.get("occupancy") in ("bathroom", "ensuite", "wc") and not (
                c.get("floor") in ("floor-wet", "floor-ensuite") and c.get("wall") == "wall-tile-wet"):
            p.append(f"room {rid}: wet room without the wet-room floor and wall finish")
    for rid in ch.get("rooms", {}):
        if rid not in design_rooms:
            p.append(f"room {rid}: not in the design model")
    return p
