RERUN = """## How to re-run (one command)

```
cd <repo> && ~/archpipe/envs/laneP-venv/bin/python -m archpipe.lightverify --design D1 --scene <scene.json>
```
* `--scene` is the workstation-built production scene (INT2's, once it exists); V3 tests every sensor against its geometry. Without it the newest
  existing candidate is used and named below. Exit status 1 = at least one layer has a failing check (this report says which); 0 = none.
* Radiance baseline (V5-V7): the frozen per-cluster results in `knowledge/lighting-verify/radiance/` (regenerated on the L6c design, `villa_run --tag lv3`).
  To regenerate them from the current design first (about 25 min, CPU): add `--regen-radiance` (and `--freeze` to overwrite the frozen baseline).
* Cycles (V5 and the single-light orientation probe) goes through `~/archpipe/bin/jobq` (GPU lock); results are cached by job hash, so a re-run with an
  unchanged design takes minutes, a changed design a few GPU jobs. `--no-cycles` skips them (V5 then cannot pass); `--skip-v8` skips the mutation layer.
* Tests: `NO_COLOR=1 PYTHONPATH=src python -m pytest tests/lightverify -q` (the two orientation tests need Blender + jobq).
"""


def render(villa, layers, meta=None) -> str:
    from ..lightcalc.villa import CLUSTERS, cluster_of
    out = ["# LV verification report (D1)", "",
           "Generated by `python -m archpipe.lightverify --design D1`. A room is **verified** only when every layer that applies to it is `pass`; "
           "`FAIL` and `n/e` (not evaluated) both make it **unverified**. Thresholds: docs/quality/LIGHTING-VERIFICATION.md.", ""]
    if meta:
        out += ["Design: `%s`. Scene used for V3: `%s` (sha256 `%s`, %s). Radiance baseline: `%s`." % (meta.get("design", "D1"), meta.get("scene"), meta.get("scene_sha256"), meta.get("scene_note", ""), meta.get("rad"))]
        out.append("")
    out += [RERUN]
    out += ["## Layers", "", "| layer | pass | fail | not evaluated | notes |", "|---|---|---|---|---|"]
    for k in sorted(layers, key=lambda s: int(s[1:])):
        c = defaultdict(int)
        for r in layers[k].results:
            c[r.status] += 1
        out.append("| %s | %d | %d | %d | %s |" % (k, c["pass"], c["fail"], c["not_evaluated"], "; ".join(str(n) for n in layers[k].notes if isinstance(n, str))[:300]))
    out.append("")
    # global gates that apply to every room
    glob = {}
    for k in ("V4", "V8"):
        sts = {r.status for r in layers[k].results}
        glob[k] = "FAIL" if "fail" in sts else ("pass" if sts == {"pass"} else ("n/e" if not sts else "pass*"))
    out += ["Global layers (apply to all rooms; V10 is per room: a room is only as verified as its bound products; a room with generic fittings only has none to check): " + ", ".join("%s %s" % (k, v) for k, v in glob.items()) +
            "  (`pass*` = passes, some points not evaluable: see the layer tables)", ""]
    v3 = {r.subject: r.status for r in layers["V3"].results}
    v12 = {r.subject: r.status for r in layers["V12"].results}
    planes = villa.planes()
    by_room = defaultdict(list)
    for p in planes:
        by_room[p.room].append(p)
    out += ["## Per room x scene", "",
            "| room | scene | plane | inputs V1 | placement V2 | sensors V3 | engines V5 | hand V6 | convergence V7 | maker data V10 | headroom V12 | status |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    n_ok = n_all = 0
    for room in sorted(by_room):
        for p in by_room[room]:
            st = {"V1": layers["V1"].room_status(room), "V2": layers["V2"].room_status(room), "V3": v3.get(p.id), "V5": layers["V5"].room_status(room),
                  "V6": layers["V6"].room_status(room), "V7": layers["V7"].room_status(room) if layers["V7"].rooms else None,
                  "V10": layers["V10"].room_status(room),
                  "V12": v12.get(p.id) if not p.id.startswith("room-") else "pass"}
            ok = all(v == "pass" for v in st.values()) and glob["V4"].startswith("pass") and glob["V8"].startswith("pass")
            n_all += 1
            n_ok += ok
            out.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
                room, p.scene, p.id, *(SYM.get(st[k]) for k in ("V1", "V2", "V3", "V5", "V6", "V7", "V10", "V12")), "**verified**" if ok else "unverified"))
    out += ["", "Verified %d of %d room-plane rows." % (n_ok, n_all), ""]
    for k in ("V1", "V5", "V6", "V7", "V4", "V10", "V12", "V8"):
        out += ["## %s detail" % k, ""]
        for r in layers[k].results:
            out.append("- %s `%s`: %s" % (SYM[r.status], r.subject, r.message))
        out.append("")
    return "\n".join(out)
