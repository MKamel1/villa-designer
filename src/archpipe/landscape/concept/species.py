"""The planting pool: ONLY species LDL marks viable or viable_with_conditions, conditions carried along.

Everything comes from knowledge/landscape/plants/plants.json (generated by LDL) and assets.json. A GAP
attribute is carried as None and never filled; a species whose size is a GAP is `size_gap`.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path

PL = Path(__file__).resolve().parents[4] / "knowledge" / "landscape" / "plants"
ALLOWED = ("viable", "viable_with_conditions")
WATER_MAP = {"very_low": "low", "low": "low", "moderate": "medium", "high": "high", "aquatic": "high"}   # LDK hydrozone vocabulary
SUN_NEED_H = {"full_sun": 6.0, "part_shade": 2.0, "shade": 0.0}                                          # policy; NCSU "6+ h" / "2-6 h"


def _v(rec, key):
    a = rec["attributes"][key]
    return a["value"] if a["status"] == "SOURCED" else None


@dataclass
class Sp:
    slug: str
    name: str
    verdict: str
    conditions: list
    layers: list
    form: str
    h_min: float | None
    h_max: float | None
    s_min: float | None
    s_max: float | None
    water: str | None          # LDK class, None = GAP
    sun_classes: list
    toxic: str | None          # class or None (GAP)
    habit: str | None
    drawable: str
    pond: bool
    invasive: bool
    flower_colours: list = field(default_factory=list)
    flower_months: list = field(default_factory=list)

    @property
    def size_gap(self):
        return self.s_max is None or self.h_max is None

    @property
    def is_toxic(self):
        return self.toxic in ("toxic", "highly_toxic")


# our form classification for the LDK soil-depth vocabulary
FORM = {"olea_europaea": "small_tree", "punica_granatum": "small_tree", "ficus_carica": "small_tree", "plumeria_rubra": "small_tree",
        "jacaranda_mimosifolia": "large_tree", "delonix_regia": "large_tree", "tipuana_tipu": "large_tree",
        "phoenix_dactylifera": "large_tree", "cupressus_sempervirens": "large_tree",
        "gazania_rigens": "ground_cover", "lantana_montevidensis": "ground_cover", "origanum_majorana": "ground_cover",
        "salvia_leucantha": "shrub", "muhlenbergia_capillaris": "ground_cover"}


# Client-decided admissions (garden-brief-2026-11-22 "climbers"): LDL leaves these "unverified" only for the unmeasured site soil (alkaline-soil GAP); frost and heat pass.
# They enter the pool with the GAP carried as a condition, not filled. Placement constraints from LDL (toxic: away from seats and herbs) are enforced by LDG-POL-TOXIC.
CLIENT_ADMIT = {"trachelospermum_jasminoides": "client decision 2026-11-22 (star jasmine on screens and walls away from seats and herbs)"}


@lru_cache(maxsize=1)
def pool() -> dict[str, Sp]:
    data = json.load(open(PL / "plants.json"))
    assets = {a["slug"]: a for a in json.load(open(PL / "assets.json"))["species"]}
    out = {}
    for r in data["species"]:
        sv = r["site_viability"]
        admitted = r["slug"] in CLIENT_ADMIT and sv["verdict"] == "unverified" and set(sv["factors"].values()) <= {"pass", "unknown"} and sv["factors"].get("alkaline_soil") == "unknown"
        if sv["verdict"] not in ALLOWED and not admitted:
            continue
        h, s = _v(r, "height_m"), _v(r, "spread_m")
        w = _v(r, "water")
        t = _v(r, "toxicity_people")
        sun = _v(r, "sun")
        fol = _v(r, "foliage")
        fl = _v(r, "flowering") or {}
        out[r["slug"]] = Sp(
            r["slug"], _v(r, "accepted_name")["name"], "viable_with_conditions" if admitted else sv["verdict"], list(sv.get("reasons", [])) + ([CLIENT_ADMIT[r["slug"]]] if admitted else []), r["layers"],
            FORM.get(r["slug"], "shrub"), h and h["min"], h and h["max"], s and s["min"], s and s["max"],
            WATER_MAP.get(w["hydrozone"]) if w else None, sun["classes"] if sun else [], t["class"] if t else None,
            fol["habit"] if fol else None, assets[r["slug"]]["drawable"], r["pond_relevant"],
            bool(r.get("invasive_flag")), fl.get("colours", []), fl.get("months", []))
    return out


def held_back() -> list[dict]:
    """Species outside the pool (heat GAP etc.): not scheduled; listed as what would unlock a richer scheme."""
    data = json.load(open(PL / "plants.json"))
    return [{"slug": r["slug"], "verdict": r["site_viability"]["verdict"], "layers": r["layers"],
             "reasons": r["site_viability"].get("reasons", [])}
            for r in data["species"] if r["site_viability"]["verdict"] not in ALLOWED]


def sun_ok(sp: Sp, june_hours: float) -> str:
    """pass / conditional / fail for a bed's mean 21-June direct sun against the species' sun class (policy thresholds)."""
    if not sp.sun_classes:
        return "unknown"
    need = min(SUN_NEED_H[c] for c in sp.sun_classes)
    if june_hours >= need:
        return "pass"
    return "conditional" if june_hours >= 0.75 * need else "fail"
